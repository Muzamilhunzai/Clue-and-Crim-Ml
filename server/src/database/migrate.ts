import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { config } from '../config';
import type { Db } from './connection';

export interface MigrationResult {
  applied: string[];
  skipped: string[];
}

const checksum = (sql: string) => crypto.createHash('sha256').update(sql).digest('hex').slice(0, 16);

/**
 * Repeatable schema initialisation: applies every database/migrations/NNN_*.sql
 * file exactly once, in order, each inside its own transaction. Applied
 * migrations are recorded in schema_migrations together with a checksum so an
 * edited, already-applied migration is detected instead of silently ignored.
 */
export function migrate(db: Db, dir: string = config.migrationsDir): MigrationResult {
  db.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    name       TEXT PRIMARY KEY,
    checksum   TEXT NOT NULL,
    applied_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
  )`);

  const files = fs.readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
  const done = new Map(
    (db.prepare('SELECT name, checksum FROM schema_migrations').all() as { name: string; checksum: string }[]).map(
      (r) => [r.name, r.checksum],
    ),
  );

  const result: MigrationResult = { applied: [], skipped: [] };
  for (const file of files) {
    const sql = fs.readFileSync(path.join(dir, file), 'utf8');
    const sum = checksum(sql);
    if (done.has(file)) {
      if (done.get(file) !== sum) {
        throw new Error(`Migration ${file} was changed after it was applied. Create a new migration instead.`);
      }
      result.skipped.push(file);
      continue;
    }
    db.transaction(() => {
      db.exec(sql);
      db.prepare('INSERT INTO schema_migrations (name, checksum) VALUES (?, ?)').run(file, sum);
    }).immediate();
    result.applied.push(file);
  }
  return result;
}

/** Concatenate all migrations into one reference file (database/schema.sql). */
export function buildSchemaFile(dir: string = config.migrationsDir): string {
  const files = fs.readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
  const header =
    '-- =====================================================================\n' +
    '-- TraceNet full schema (GENERATED by `npm run db:schema` from database/migrations/*.sql)\n' +
    '-- Do not edit by hand: change or add a migration, then regenerate.\n' +
    '-- =====================================================================\n\n';
  return header + files.map((f) => `-- >>> ${f}\n${fs.readFileSync(path.join(dir, f), 'utf8')}`).join('\n');
}
